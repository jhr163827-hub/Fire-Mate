const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({viewport:{width:390,height:844}});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/index.html');
 await page.locator('#fmManualUpdate').waitFor();
 assert.equal(await page.locator('#view-home').count(),1);
 assert.equal(await page.locator('#view-assets').count(),1);
 await page.locator('[data-view="calendar"]').last().click();
 await page.locator('#view-calendar.active').waitFor();
 await page.locator('#fmLedgerAddBtn').click();
 await page.locator('#entryOverlay.show').waitFor();
 await page.locator('#entryAmount').fill('12345');
 await page.locator('#entryDate').fill('2026-10-15');
 await page.locator('#entryMemo').fill('E2E verification');
 await page.locator('#saveEntry').click();
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('firemate_smart_v3')||'{}').tx?.some(x=>x.memo==='E2E verification'&&x.amount===12345));
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('firemate_smart_v3')));
 await page.reload();
 assert.ok(await page.evaluate(()=>JSON.parse(localStorage.getItem('firemate_smart_v3')).tx.some(x=>x.memo==='E2E verification'&&x.amount===12345)),'Ledger record lost');
 await page.locator('[data-view="assets"]').last().click();
 await page.locator('#view-assets.active').waitFor();
 await page.locator('#refreshStocks').click();
 await page.waitForTimeout(300);
 assert.ok(await page.evaluate(()=>JSON.parse(localStorage.getItem('firemate_smart_v3')).tx.some(x=>x.memo==='E2E verification'&&x.amount===12345)),'Ledger record lost');
 await page.locator('#fmManualUpdate').click();
 await page.waitForTimeout(600);
 assert.ok(await page.evaluate(()=>JSON.parse(localStorage.getItem('firemate_smart_v3')).tx.some(x=>x.memo==='E2E verification'&&x.amount===12345)),'Ledger record lost');
 console.log('Browser page errors:',errors);
 const registration=await page.evaluate(async()=>{const r=await navigator.serviceWorker.ready;return {active:!!r.active,controlled:!!navigator.serviceWorker.controller}});
 assert.equal(registration.active,true);
 await context.setOffline(true);
 await page.reload();
 await page.locator('#view-home').waitFor();
 assert.ok(await page.evaluate(()=>JSON.parse(localStorage.getItem('firemate_smart_v3')).tx.some(x=>x.memo==='E2E verification'&&x.amount===12345)),'Ledger record lost');
 await browser.close();
 console.log('PASS: navigation, ledger save/reload, stock refresh without key, update no-op, SW offline reload, data preserved');
})().catch(e=>{console.error(e);process.exit(1)});
